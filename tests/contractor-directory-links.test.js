import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
test('directory links retain their address, expire in three years and rotate atomically with admin checks',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create table workspaces(id uuid primary key,owner_id uuid);
 create table workspace_members(workspace_id uuid,user_id uuid,role text);
 create table contractor_directory_links(workspace_id uuid primary key,token text unique,expires_at timestamptz,created_by uuid,created_at timestamptz default now());
 insert into workspaces values('10000000-0000-4000-8000-000000000001','20000000-0000-4000-8000-000000000001');
 insert into contractor_directory_links values('10000000-0000-4000-8000-000000000001','existing-address',now()+interval '20 days','20000000-0000-4000-8000-000000000001',now()-interval '10 days');`);
 await db.exec(await readFile(new URL('../supabase/contractor_directory_long_lived.sql',import.meta.url),'utf8'));
 assert.deepEqual((await db.query(`select token,expires_at=created_at+interval '3 years' as extended from contractor_directory_links`)).rows[0],{token:'existing-address',extended:true});
 const ws='10000000-0000-4000-8000-000000000001';
 await assert.rejects(db.query('select regenerate_contractor_directory_link($1)',[ws]),/permission/);
 await db.exec(`set test.uid='20000000-0000-4000-8000-000000000001'`);
 const first=(await db.query('select manage_contractor_directory_link($1,false) link',[ws])).rows[0].link;
 assert.equal(first.token,'existing-address');
 const rotated=(await db.query('select regenerate_contractor_directory_link($1) link',[ws])).rows[0].link;
 assert.notEqual(rotated.token,first.token);
 assert.equal((await db.query("select expires_at between now()+interval '3 years'-interval '5 seconds' and now()+interval '3 years'+interval '5 seconds' as full_term from contractor_directory_links")).rows[0].full_term,true);
 await db.query('select manage_contractor_directory_link($1,true)',[ws]);
 assert.equal((await db.query('select count(*)::int n from contractor_directory_links')).rows[0].n,0);
 const fresh=(await db.query('select manage_contractor_directory_link($1,false) link',[ws])).rows[0].link;
 assert.notEqual(fresh.token,rotated.token);
 assert.equal((await db.query("select has_function_privilege('anon','public.regenerate_contractor_directory_link(uuid)','EXECUTE') allowed")).rows[0].allowed,false);
 await db.close();
});
