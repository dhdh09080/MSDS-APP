import {test} from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
test('document transfer is scoped, atomic, authorized and preserves source identity',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create function public.can_manage_workspace_links(uuid) returns boolean language sql as $$select auth.uid()='00000000-0000-4000-8000-000000000001'::uuid$$;
 create table workspaces(id uuid primary key,name text,pmx_prj_cd text);
 create table contractors(id uuid primary key default gen_random_uuid(),workspace_id uuid,name text,manager_name text,manager_phone text);
 create table work_types(id int,workspace_id uuid,contractor_id uuid,name text);
 create table msds_records(workspace_id uuid,contractor text,has_pdf boolean,pdf_path text,receipt_status text);
 create table business_licenses(workspace_id uuid,contractor_id uuid);
 create table contractor_directory_links(workspace_id uuid,token text,expires_at timestamptz);
 `);
 await db.exec(await readFile(new URL('../supabase/contractor_lifecycle.sql',import.meta.url),'utf8'));
 const ws='10000000-0000-4000-8000-000000000001',a='20000000-0000-4000-8000-000000000001',b='20000000-0000-4000-8000-000000000002';
 await db.query(`insert into contractors(id,workspace_id,name) values($1,$3,'수기 업체'),($2,$3,'받는 업체')`,[a,b,ws]);
 await db.query(`insert into msds_records(workspace_id,contractor) values($1,'수기 업체')`,[ws]);
 await assert.rejects(db.query('select transfer_contractor_documents($1,$2,$3)',[ws,a,b]),/권한/);
 await db.exec(`set test.uid='00000000-0000-4000-8000-000000000001'`);
 await assert.rejects(db.query('select transfer_contractor_documents($1,$2,$3)',[ws,a,'30000000-0000-4000-8000-000000000001']),/같은 현장/);
 assert.equal((await db.query('select contractor from msds_records')).rows[0].contractor,'수기 업체');
 await db.query('select transfer_contractor_documents($1,$2,$3)',[ws,a,b]);
 assert.equal((await db.query('select contractor from msds_records')).rows[0].contractor,'받는 업체');
 assert.equal((await db.query('select is_active from contractors where id=$1',[a])).rows[0].is_active,false);
 await db.query(`insert into workspaces values($1,'테스트 현장','070120')`,[ws]);
 await assert.rejects(db.query('select import_pmx_partners($1,$2,current_date,now(),$3)',[ws,'070120',JSON.stringify([{companyNm:'롤백 업체',contracts:[]},{companyNm:'',contracts:[]}])]),/형식/);
 assert.equal((await db.query("select count(*)::int n from contractors where name='롤백 업체'")).rows[0].n,0);
 const payload=JSON.stringify([{companyNm:'받는 업체',contracts:['도장공사']},{companyNm:'신규 업체',contracts:['방수공사']}]);
 await assert.rejects(db.query('select import_pmx_partners($1,$2,current_date,now(),$3)',[ws,'999999',payload]),/현장코드/);
 for(let n=0;n<2;n++)await db.query('select import_pmx_partners($1,$2,current_date,now(),$3)',[ws,'070120',payload]);
 assert.equal((await db.query('select count(*)::int n from contractors')).rows[0].n,3);
 assert.equal((await db.query('select count(*)::int n from work_types')).rows[0].n,2);
 assert.equal((await db.query('select pmx_company_name from contractors where id=$1',[b])).rows[0].pmx_company_name,'받는 업체');
 assert.equal((await db.query('select is_active from contractors where id=$1',[a])).rows[0].is_active,false);
 await db.close();
});
